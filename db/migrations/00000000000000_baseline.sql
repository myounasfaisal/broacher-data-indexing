-- ── RLS policies ──────────────────────────────────────────────────────────
-- The backend uses the service_role key which bypasses RLS entirely — these
-- policies exist so the frontend can read the catalog directly with an
-- authenticated anon-key session. Every write path goes through the backend.
-- DROP-then-CREATE for idempotency (Postgres has no CREATE POLICY IF NOT EXISTS).

DROP POLICY IF EXISTS "read own profile"                    ON public.profiles;
CREATE POLICY "read own profile"                            ON public.profiles
  FOR SELECT USING (auth.uid() = id);

DROP POLICY IF EXISTS "authenticated read chemicals"        ON public.chemicals;
CREATE POLICY "authenticated read chemicals"                ON public.chemicals
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "authenticated read listings"         ON public.listings;
CREATE POLICY "authenticated read listings"                 ON public.listings
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "authenticated read documents"        ON public.documents;
CREATE POLICY "authenticated read documents"                ON public.documents
  FOR SELECT TO authenticated USING (true);

-- Documents/pages have an EXTRA admin-manager read policy on top of the
-- authenticated one because some admin queries widened the row-level filter
-- beyond what the base policy already implies (SELECT true). Kept for parity
-- with production; they are additive, not restrictive.
DROP POLICY IF EXISTS "admin_manager read documents"        ON public.documents;
CREATE POLICY "admin_manager read documents"                ON public.documents
  FOR SELECT TO authenticated USING (EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid() AND profiles.role = ANY (ARRAY['admin','manager'])
  ));

DROP POLICY IF EXISTS "admin_manager read pages"            ON public.pages;
CREATE POLICY "admin_manager read pages"                    ON public.pages
  FOR SELECT TO authenticated USING (EXISTS (
    SELECT 1 FROM public.profiles
    WHERE profiles.id = auth.uid() AND profiles.role = ANY (ARRAY['admin','manager'])
  ));

DROP POLICY IF EXISTS "authenticated read chemical_embeddings" ON public.chemical_embeddings;
CREATE POLICY "authenticated read chemical_embeddings"         ON public.chemical_embeddings
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "authenticated read substitution_notes"  ON public.substitution_notes;
CREATE POLICY "authenticated read substitution_notes"          ON public.substitution_notes
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "authenticated read regulatory_notes"    ON public.regulatory_notes;
CREATE POLICY "authenticated read regulatory_notes"            ON public.regulatory_notes
  FOR SELECT TO authenticated USING (true);


-- ── Storage: the brochure-pages bucket ────────────────────────────────────
-- Private bucket; the backend uploads and reads with the service_role key,
-- which bypasses RLS. No storage.objects policies are needed and none exist in
-- production. If a future feature ever needs direct browser access to a page
-- image, add policies here — do not make the bucket public.

INSERT INTO storage.buckets (id, name, public)
VALUES ('brochure-pages', 'brochure-pages', false)
ON CONFLICT (id) DO NOTHING;


-- ── Function grants ───────────────────────────────────────────────────────
-- service_role only. The browser never invokes these RPCs directly; the
-- backend does, holding the service key. Explicit REVOKE first so re-running
-- cannot silently widen access.

REVOKE ALL ON FUNCTION public.claim_next_document(text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.search_text(listings)     FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.details_text(listings)    FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.match_chemicals(text, integer, uuid, real)
                                                        FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.claim_next_document(text) TO service_role;
GRANT EXECUTE ON FUNCTION public.search_text(listings)     TO service_role;
GRANT EXECUTE ON FUNCTION public.details_text(listings)    TO service_role;
GRANT EXECUTE ON FUNCTION public.match_chemicals(text, integer, uuid, real)
                                                           TO service_role;
